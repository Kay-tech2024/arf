        public static string GenerateNIN()
        {
            var nin = null as string;

            while (true)
            {
                nin = rand.Next(0, 10) <= 8 ? "10" : "20";

                for (var i = 0; i < 8; i++)
                {
                    nin += rand.Next(0, 9);
                }

                if (AbstractManager.IsValidNationalId(nin))
                {
                    break;
                }
            }

            return nin;
        }

        public static string GenerateMobileNumber()
        {
            var mobile = "5";
            for (var i = 0; i < 8; i++)
            {
                mobile += rand.Next(0, 9);
            }

            return mobile;
        }

        public static string GenerateName(out char gender)
        {
            var firstNameEntry = FirstNamesWithGenders.OrderBy(k => k.Key).ToArray()[rand.Next(0, FirstNamesWithGenders.Count)];
            gender = firstNameEntry.Value;
            return firstNameEntry.Key + " " + MiddleNames.OrderBy(k => k).ToArray()[rand.Next(0, MiddleNames.Count)] + " " + LastNames.OrderBy(k => k).ToArray()[rand.Next(0, LastNames.Count)];
        }

        public static string GenerateEstabilishmentName(out long estId)
        {
            var firstNameEntry = Establishments.OrderBy(k => k.Key).ToArray()[rand.Next(0, Establishments.Count)];
            estId = firstNameEntry.Value;
            return firstNameEntry.Key;
        }

